function norm(ch: string, f: Font): string {
  if (ch === '’' || ch === '‘') return "'";
  if (ch === '“' || ch === '”') return '"';
  if (ch === '—' || ch === '–') return '-';
  return f.upper ? ch.toUpperCase() : ch;
}

export function measure(text: string, f: Font): number {
  let w = 0;
  for (const raw of text) {
    const ch = norm(raw, f);
    if (ch === ' ') { w += f.space + f.gap; continue; }
    const g = f.glyphs[ch];
    w += (g ? g.w : 3) + f.gap;
  }
  return Math.max(0, w - f.gap);
}

/** Draw text; returns width. `shadow` draws a 1px drop shadow beneath (down-right). */
export function text(s: Surface, str: string, x: number, y: number, c: Col, f: Font = BODY, shadow?: Col): number {
  let cx = x;
  for (const raw of str) {
    const ch = norm(raw, f);
    if (ch === ' ') { cx += f.space + f.gap; continue; }
    const g = f.glyphs[ch];
    if (!g) { cx += 3 + f.gap; continue; }
    for (let r = 0; r < g.rows.length; r++) {
      const row = g.rows[r];
      for (let i = 0; i < row.length; i++) if (row[i] === '#') {
        if (shadow) s.px(cx + i + 1, y + r + 1, shadow);
        s.px(cx + i, y + r, c);
      }
    }
    cx += g.w + f.gap;
  }
  return cx - x - f.gap;
}

/** Word-wrap to a pixel width. */
export function wrap(str: string, maxW: number, f: Font = BODY): string[] {
  const out: string[] = [];
  for (const para of str.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (measure(t, f) > maxW && line) { out.push(line); line = word; } else line = t;
    }
    out.push(line);
  }
  return out;
}
