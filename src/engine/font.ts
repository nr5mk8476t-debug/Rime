// Hand-built bitmap fonts so text sits on the same pixel grid as the art.
//  - BODY: 5x7 proportional with lowercase + descenders (dialogue, tooltips, screens)
//  - TINY: 3x5 caps (signage, labels, small readouts)

import type { Surface } from './surface';
import type { Col } from './palette';

interface Glyph { w: number; rows: string[] }
export interface Font { glyphs: Record<string, Glyph>; h: number; line: number; space: number; gap: number; upper: boolean }

function build(src: Record<string, string>, h: number, line: number, space: number, upper: boolean): Font {
  const glyphs: Record<string, Glyph> = {};
  for (const k in src) {
    const rows = src[k].split('|');
    glyphs[k] = { w: Math.max(...rows.map((r) => r.length)), rows };
  }
  return { glyphs, h, line, space, gap: 1, upper };
}

